  const DICOS = { fr, en, es, ar };
  const LANGUES = Object.keys(DICOS);
  let langue = "fr";
  let pluriel = new Intl.PluralRules("fr");

  function locale() {
    return langue === "ar" ? "ar-u-nu-latn" : langue;
  }

  function langueNavigateur() {
    for (const l of navigator.languages || [navigator.language || "fr"]) {
      const base = String(l).slice(0, 2).toLowerCase();
      if (LANGUES.includes(base)) return base;
    }
    return "fr";
  }

  function choisir(l) {
    langue = LANGUES.includes(l) ? l : "fr";
    pluriel = new Intl.PluralRules(locale());
  }

  /** Texte traduit ; {cle} remplacé par params.cle ; formes plurielles choisies selon params.n. */
  function t(cle, params) {
    let v = DICOS[langue][cle];
    if (v == null) v = fr[cle];
    if (v == null) return cle;
    if (typeof v === "object") {
      const n = params && typeof params.n === "number" ? params.n : 0;
      const forme = n === 0 && v.zero ? "zero" : pluriel.select(n);
      v = v[forme] || v.other || Object.values(v)[0];
    }
    if (params) {
      v = v.replace(/\{(\w+)\}/g, (_, k) => {
        const x = params[k];
        return x == null ? "" : typeof x === "number" ? new Intl.NumberFormat(locale(), { maximumFractionDigits: 2 }).format(x) : String(x);
      });
    }
    return v;
  }

  function nommer(type, code, enLangue) {
    try {
      return new Intl.DisplayNames([enLangue || locale()], { type, fallback: "code" }).of(code) || code;
    } catch (e) {
      return code;
    }
  }

